import * as React from "react"

import {
  Breadcrumb,
  BreadcrumbItem,
  BreadcrumbLink,
  BreadcrumbList,
  BreadcrumbPage,
  BreadcrumbSeparator,
} from "@/components/shadcn/breadcrumb"
import { Button } from "@/components/shadcn/button"
import { cn } from "@/lib/utils"

import { contacts } from "@/views/portfolio.data"

/**
 * Шапка, футер и хлебные крошки.
 *
 * В реестре shadcn их нет по определению (это композиция страницы, а не
 * примитив), но всё, из чего они собраны, — оттуда: контакт это `Button`
 * варианта `ghost` с радиусом-таблеткой.
 *
 * Ссылка обозначается подчёркиванием и весом 500, а не цветом: хроматики в
 * интерфейсе нет вовсе, и цвет как единственный признак состояния запрещён
 * (WCAG 1.4.1).
 *
 * ─── ЦЕЛЬ НАЖАТИЯ ───────────────────────────────────────────────────────────
 * Высота цели поднята до 44 px паддингом, а НЕ кеглем: текст остаётся в
 * интерфейсном регистре 14/20, растёт только область нажатия. Первая сборка
 * дала здесь 20 px — высоту строки: у текстовой кнопки без паддинга цель равна
 * глифам, и WCAG 2.5.8 (минимум 24) не выполнялся, а практический ориентир для
 * пальца — 44. Компенсирующий отрицательный отступ держит текст на прежней
 * оптической линии, чтобы выросшая цель не раздвинула шапку.
 */

/** Текстовая цель нажатия: 44 px на тач-ширинах, компактнее на десктопе. */
const TAP_TARGET = "inline-flex min-h-11 items-center px-2 -mx-2 sm:min-h-9"

export interface SiteHeaderProps {
  /**
   * Уровни выше текущего, слева направо, БЕЗ имени автора — оно всегда первое
   * звено и добавляется само. На главной массив пуст.
   */
  levels?: { label: string; onClick: () => void }[]
  /**
   * Подпись текущей страницы. На главной не передаётся: там текущая страница —
   * сам автор, и цепочка состоит из одного звена.
   */
  current?: string
  /** Переход на главную. Не передаётся на самой главной — имя там не ссылка. */
  onHome?: () => void
}

/**
 * Шапка — одна цепочка: «Иван Игнатов · А3 · Редизайн главной».
 *
 * ─── ПОЧЕМУ КРОШКИ ЗДЕСЬ, А НЕ ПОД ШАПКОЙ (правка владельца 2026-08-03) ─────
 * Раньше это были два разных блока: шапка с именем и отдельная строка крошек
 * под ней. На главной второго блока нет, на внутренних есть — и содержимое
 * стартовало с разной высоты, из-за чего сайт «дёргался» при переходе. Имя и
 * первое звено крошек к тому же означали одно и то же место (главную) и
 * стояли друг под другом.
 *
 * Слитая цепочка убирает лишний уровень: у всех трёх страниц одна и та же
 * шапка одной и той же высоты, отличается только длина цепочки. Слово
 * «Главная» больше не нужно — его роль взяло имя автора; новых строк текста
 * при этом не заведено, «Иван Игнатов» на сайте уже был.
 *
 * Имя остаётся чернилами и весом 500 даже когда оно — уровень выше: это
 * подпись автора, а не рядовое звено пути.
 *
 * ─── ПОЧЕМУ КОНТАКТОВ ЗДЕСЬ НЕТ ─────────────────────────────────────────────
 * До правки того же дня шапка и подвал несли ОДИН И ТОТ ЖЕ набор `contacts[]`
 * — буквально три одинаковые ссылки в двух местах страницы. Дубль пришёл из
 * спецификации (`screens.md`, строки `header` и `footer`) и прошёл всю
 * машинную приёмку: обе строки по отдельности корректны, а то, что они
 * совпадают, ни один тест не проверяет. Заметил владелец.
 *
 * Замер образцов (2026-08-03, `getComputedStyle` + разбор ссылок): у
 * `seconddesk.ai` шапка 64 px / 7 ссылок, подвал 358 px / 10 ссылок в трёх
 * группах, пересечение 4 — подвал НАДМНОЖЕСТВО шапки, а не её копия; у
 * `supabase.com` пересечение нулевое. Ни у одного подвал не равен шапке.
 * Скопировать их структуру нечем: у портфолио нет разделов, которые ложатся
 * в колонки, — единственная связь наружу это контакт. Поэтому разведены
 * роли, а не состав: сверху путь, снизу действие.
 */
export function SiteHeader({ current, levels = [], onHome }: SiteHeaderProps) {
  /* Имя — первое звено цепочки. Ссылкой оно становится только там, откуда
     есть куда вести: на самой главной ссылка на текущую страницу была бы
     обещанием перехода, которого не будет. */
  const name = "Иван Игнатов"
  const trail = onHome ? [{ label: name, onClick: onHome }, ...levels] : levels

  return (
    <header className="pf-container flex items-center py-6" data-testid="pf-header">
      <Breadcrumb>
        <BreadcrumbList className="pf-ui">
          {trail.map((level, index) => (
            <React.Fragment key={level.label}>
              <BreadcrumbItem>
                <BreadcrumbLink asChild>
                  {/* Имя автора подчиняется правилам цепочки наравне с
                      остальными звеньями: уровень выше — приглушённый, текущая
                      страница — чернила. Отдельного начертания у него нет.
                      Первая сборка держала имя чернилами и весом 500 всегда, и
                      на внутренних страницах два звена из трёх читались как
                      текущее место. Правка владельца 2026-08-03. */}
                  <button
                    className={cn(TAP_TARGET, "pf-crumb pf-focus pf-motion rounded-sm")}
                    data-testid={index === 0 ? "pf-header-home" : `pf-crumb-${level.label}`}
                    onClick={level.onClick}
                    type="button"
                  >
                    {level.label}
                  </button>
                </BreadcrumbLink>
              </BreadcrumbItem>
              <BreadcrumbSeparator>·</BreadcrumbSeparator>
            </React.Fragment>
          ))}
          <BreadcrumbItem>
            {/* Чернила приходят от `BreadcrumbPage` из реестра — здесь только
                вес: текущее место должно читаться как текущее и на главной,
                где цепочка состоит из одного звена. */}
            <BreadcrumbPage className={cn(TAP_TARGET, "font-medium")} data-testid="pf-header-current">
              {current ?? name}
            </BreadcrumbPage>
          </BreadcrumbItem>
        </BreadcrumbList>
      </Breadcrumb>
    </header>
  )
}

export interface SiteFooterProps {
  className?: string
  onContact?: (channel: string) => void
  /**
   * Показывать ли блок контакта. Выключается там, где контакт УЖЕ живёт на
   * странице — на кейсе его держит липкая правая колонка.
   */
  contact?: boolean
  /** Хвост подписи: «портфолио» на главной, имя компании на внутренней. */
  suffix?: string
}

/**
 * Подвал — закрывающее действие сайта, а не повтор шапки.
 *
 * Контакт стоит здесь, а не наверху: на портфолио написать автору — целевое
 * действие, и его место в конце просмотра работ, а не до него. Разбор дубля
 * шапки и подвала — в комментарии к `SiteHeader`.
 *
 * Заголовок «Обсудить задачу» не сочинён: этой строкой уже подписан блок
 * контакта в правой колонке кейса (`CaseAside`). Ярлыки каналов — те же
 * `tg`/`email`/`linkedin` из данных. Ни одной новой строки текста.
 *
 * Кнопки повторяют приём `CaseAside`: заливка достаётся первому каналу,
 * остальные — `outline`. Три одинаковые кнопки подряд читались бы как три
 * главных действия, то есть ни одно.
 *
 * На странице кейса блок выключен (`contact={false}`): там контакт уже
 * сопровождает чтение в липкой колонке, и второй такой же блок внизу вернул
 * бы ровно тот дубль, ради которого правка и делалась, — только внутри одной
 * страницы.
 */
export function SiteFooter({
  className,
  contact = true,
  onContact,
  suffix = "портфолио",
}: SiteFooterProps) {
  return (
    <footer className={cn("border-border mt-24 border-t", className)} data-testid="pf-footer">
      <div className="pf-container py-10">
        {contact ? (
          <div className="mb-10">
            <p className="pf-ui text-foreground mb-3 font-semibold">Обсудить задачу</p>
            <div className="flex flex-wrap items-center gap-2">
              {contacts.map((channel, index) => (
                <Button
                  asChild
                  className="pf-ui h-11 sm:h-9"
                  key={channel.label}
                  size="sm"
                  variant={index === 0 ? "default" : "outline"}
                >
                  <a
                    data-testid={`pf-footer-${channel.label}`}
                    href={channel.href}
                    onClick={() => onContact?.(channel.label)}
                    rel={channel.external ? "noreferrer" : undefined}
                    target={channel.external ? "_blank" : undefined}
                  >
                    {channel.label}
                  </a>
                </Button>
              ))}
            </div>
          </div>
        ) : null}

        <span className="pf-ui pf-ink-soft">© 2026 Иван Игнатов · {suffix}</span>
      </div>
    </footer>
  )
}
