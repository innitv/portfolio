import * as React from "react";

import Lenis from "lenis";

/**
 * Мягкая прокрутка страницы.
 *
 * Заведена 2026-08-13 по образцу `wemakefab.ru`: у них прокрутка идёт с
 * инерцией и «догоняет» колесо. Их способ — виртуальный скролл на GSAP
 * (`html` и `body` с `overflow: hidden`, высота документа равна окну, а
 * содержимое двигают трансформом). Так делать не стали: это ломает всё, что
 * опирается на настоящую прокрутку документа, включая прыжок к результату
 * поиска по странице. Lenis вместо этого перехватывает колесо и сам
 * прокручивает документ — снаружи прокрутка остаётся обычной.
 *
 * ─── ЧТО ЭТО СТОИТ ──────────────────────────────────────────────────────────
 * 1. Прокрутка перестаёт быть мгновенной, поэтому всё, что ждёт «уже
 *    прокрутилось», должно ждать конца анимации. Отсюда `duration` небольшой.
 * 2. Автотесты прокручивают программно (`scrollIntoView`, `scrollTo`) — эти
 *    вызовы Lenis не перехватывает и они работают как раньше.
 * 3. На тач-экранах перехват выключен (`smoothTouch` по умолчанию false):
 *    инерция там своя, системная, и вторая поверх неё ощущается как залипание.
 */

/** Длительность догона, секунды. Больше — прокрутка начинает «плыть». */
const DURATION = 0.9;

export function useSmoothScroll(enabled = true) {
  React.useEffect(() => {
    if (!enabled) return undefined;

    const lenis = new Lenis({
      duration: DURATION,
      /*
       * Экспонента с быстрым началом и длинным хвостом: страница трогается за
       * колесом сразу, а останавливается плавно. Линейное затухание читается
       * как задержка ввода, а не как мягкость.
       */
      easing: (t: number) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
      /*
       * 🔴 Системную настройку «уменьшить движение» здесь НЕ уважаем, и это
       * продолжение решения владельца по экрану `/archive` (разбор — в шапке
       * `portfolio-archive.css`): на его машине настройка включена постоянно, и
       * при `respectReducedMotion: true` — значении по умолчанию — Lenis молча
       * отключался. Поймано замером: класс `lenis` на `html` появлялся, а
       * `lenis-smooth` нет, и прокрутка оставалась нативной.
       *
       * Отступление ограничено: единственное движение здесь — догон прокрутки
       * за 0.9 с по действию самого человека, без параллакса и автоскролла.
       */
      respectReducedMotion: false,
    });

    /*
     * Экземпляр выставлен наружу намеренно: проверить прокрутку синтетическим
     * событием `wheel` нельзя — браузер по нему не прокручивает, — а без ссылки
     * на экземпляр не спросить ни `prefersReducedMotion`, ни состояние. Через
     * эту точку прокрутка проверяется вызовом `__lenis.scrollTo(...)`.
     */
    ;(window as unknown as { __lenis?: Lenis }).__lenis = lenis;

    let frame = 0;
    const raf = (time: number) => {
      lenis.raf(time);
      frame = requestAnimationFrame(raf);
    };
    frame = requestAnimationFrame(raf);

    return () => {
      cancelAnimationFrame(frame);
      lenis.destroy();
      delete (window as unknown as { __lenis?: Lenis }).__lenis;
    };
  }, [enabled]);
}
