import { MoveRight } from "lucide-react"
import * as React from "react"

import { CompanyLogo } from "./company-logo"

import type { Company } from "@/views/portfolio.data"

/**
 * Карточка компании на разводящей.
 *
 * ─── ОТКУДА ФОРМА ───────────────────────────────────────────────────────────
 * Оформление выбрано владельцем по нижней паре карточек блока
 * `@shadcnblocks/case-studies3`: карточка — не рамка со скруглением, а ячейка
 * общей рамки ряда. Поэтому у неё НЕТ своей границы по периметру — есть только
 * граница соседу: сверху на узкой ширине и слева на широкой. Внешний контур
 * рисует обёртка ряда в `PortfolioHomeView`.
 *
 * ─── ПОЧЕМУ ССЫЛКОЙ РАБОТАЕТ ВСЯ КАРТОЧКА ───────────────────────────────────
 * В образце кликабельна карточка целиком, а строка со стрелкой — не отдельная
 * ссылка, а подпись действия. Здесь так же: корень карточки — `button`, а
 * «Смотреть кейсы» со стрелкой лежит внутри обычным `span`. Вложенных
 * интерактивных элементов нет, а цель нажатия равна всей карточке.
 *
 * `aria-label` намеренно НЕ ставится: он подменил бы доступное имя короткой
 * фразой и отрезал бы от скринридера описание компании, которое на карточке
 * является основным содержанием.
 */

export interface CompanyCardProps {
  company: Company
  onOpen: (companyId: Company["id"]) => void
}

/** Высота знака до оптической поправки — она внутри `CompanyLogo`. */
const LOGO_HEIGHT = 19

/**
 * Двухцветная фраза: где кончаются чернила и начинается приглушённое.
 *
 * Граница берётся ПО СМЫСЛУ, а не по числу символов: сначала двоеточие (у всех
 * трёх описаний оно есть и отделяет «что это» от перечисления), иначе — конец
 * первого предложения. Нет ни того, ни другого — фраза остаётся одноцветной,
 * потому что резать её посередине хуже, чем не резать вовсе.
 */
export function splitLede(text: string): { head: string; tail: string } {
  const colon = text.indexOf(":")
  if (colon > 0) {
    return { head: text.slice(0, colon + 1), tail: text.slice(colon + 1).trim() }
  }

  const period = text.indexOf(". ")
  if (period > 0) {
    return { head: text.slice(0, period + 1), tail: text.slice(period + 2).trim() }
  }

  return { head: text, tail: "" }
}

/**
 * Общий класс ячейки ряда. Вынесен, потому что карточка кейса стоит в таком же
 * ряду и обязана делить с этой одну геометрию: разъедутся — ряды на двух
 * страницах перестанут быть одним приёмом.
 *
 * `first:` снимает границу у первой ячейки: внешний контур уже нарисован
 * обёрткой, и без этого сверху и слева получалась двойная линия.
 */
export const ROW_CELL =
  "group pf-focus bg-background hover:bg-muted/40 border-border flex cursor-pointer flex-col gap-10 border-t px-6 py-8 text-left transition-colors duration-500 ease-out first:border-t-0 md:py-14 lg:border-t-0 lg:border-l lg:first:border-l-0 xl:gap-14 xl:px-8"

/**
 * Нижний блок ячейки: надзаголовок, фраза, действие.
 *
 * `mt-auto` вместо `justify-between` на родителе. Разница видна только на
 * реальных данных: `justify-between` прижимает нижний блок к низу ячейки, и
 * тогда его ВЕРХ зависит от длины описания. Замер на трёх карточках главной
 * дал надзаголовки на 687 / 655 / 719 — разброс 64 px при том, что знаки
 * компаний выровнены (597 / 599 / 593). Ряд читался пляшущим.
 *
 * У образца (`@shadcnblocks/case-studies3`) этого не видно, потому что там
 * описания одинаковой длины. У нас 4 / 5 / 4 строки, и приём ломается.
 *
 * `mt-auto` съедает остаток высоты ДО блока, поэтому надзаголовки встают на
 * одну линию, описания растут вниз, а действие остаётся последним элементом
 * потока. Проверять надо верх надзаголовка, а не низ ячейки.
 */
export const ROW_CELL_BODY = "mt-auto pt-10"

/**
 * Ряд карточек: общая рамка вокруг ячеек.
 *
 * Живёт здесь, а не отдельным файлом, потому что владелец ячейки и владелец
 * ряда — один приём: ячейка НЕ рисует свой периметр и без этой обёртки
 * оказывается без внешнего контура. Разносить их по файлам — способ однажды
 * поставить `CompanyCard` без ряда и не заметить.
 *
 * Число колонок передаётся явными классами: Tailwind собирает утилиты по
 * литералам в исходнике, и `lg:grid-cols-${n}` в сборку не попадёт.
 */
const ROW_COLUMNS = {
  1: "lg:grid-cols-1",
  2: "lg:grid-cols-2",
  3: "lg:grid-cols-3",
} as const

/*
 * ─── ДЕКОРАТИВНЫХ ПОЛОС ПО КРАЯМ РЯДА ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ ───────────────
 * В образце ряд обрамлён полосами в точку шириной 112 px. Собрано и снято со
 * страницы: у нас полезная ширина ряда 1152, полосы забирают 224, и на колонку
 * остаётся 309 px минус поля — фраза кегля 24 встаёт колодцем в восемь строк
 * вместо пяти. Полосы у образца стоят при двух колонках и широком контейнере,
 * то есть платит за них пустое место, а у нас платит содержание.
 */

export function CardRow({
  children,
  columns,
}: {
  children: React.ReactNode
  columns: keyof typeof ROW_COLUMNS
}) {
  /* ─── РАДИУС РЯДА (правка владельца 2026-08-03) ─────────────────────────────
     Ряд карточек был единственной прямоугольной поверхностью сайта. Замер
     радиусов страниц: кнопки 8, крошки и имя в шапке 6, кадр со скриншотом 14,
     знаки героя pill — и только эта рамка 0. Скругление берётся то же, что у
     кадра (`--radius-xl`, 14 px), по уже записанному в `.pf-frame` правилу:
     кадр и карточка стоят на одной странице, и разные скругления читались бы
     как разные системы.

     `overflow-hidden` обязателен: карточки внутри собственных углов не имеют,
     а подложка `hover:bg-muted/40` у крайних из них — прямоугольная, и без
     обрезки она вылезала бы за скруглённый угол рамки при наведении. */
  return (
    <div
      className={`border-border grid overflow-hidden rounded-xl border ${ROW_COLUMNS[columns]}`}
    >
      {children}
    </div>
  )
}

export function CompanyCard({ company, onOpen }: CompanyCardProps) {
  const { head, tail } = splitLede(company.cardLede)
  /* Число кейсов из надзаголовка снято по решению владельца 2026-08-03:
     счётчик на разводящей читается как исчерпывающий список работ, тогда как
     показанное — лишь то, что можно показать. */
  const kicker = [company.industry, company.years].filter(Boolean).join(" · ")

  return (
    <button
      className={ROW_CELL}
      data-testid={`pf-company-${company.id}`}
      onClick={() => onOpen(company.id)}
      type="button"
    >
      {/* Высота строки задана явно, потому что видимого текста в ней больше
          нет. Раньше её держала подпись (18/26), и знаки разной высоты — 29,
          32 и 20 px — стояли отцентрованными по общей оси. Без подписи высота
          строки стала равна высоте самого знака, и «Самолет» поднялся на 12 px
          выше соседей. 32 px — высота самого крупного знака (РТК). */}
      <span className="flex h-8 items-center gap-3">
        <CompanyLogo className="text-foreground" company={company.id} height={LOGO_HEIGHT} />
        {/* Название компании читает только скринридер.
            ─── ПОЧЕМУ ВИДИМОГО ТЕКСТА БОЛЬШЕ НЕТ ────────────────────────────
            Все три знака словесные, и рядом с ними подпись повторяла сама
            себя: «Ростелеком РТК», «самолет Самолет» — различие только в
            регистре. Решение владельца: оставить знак, подпись снять.
            ─── ПОЧЕМУ `sr-only`, А НЕ ПРОСТО УДАЛИТЬ ────────────────────────
            Знак — `aria-hidden`, потому что это вставленный SVG; без этой
            строки в доступном имени кнопки не осталось бы имени компании
            вовсе, и карточка звучала бы как «B2B-платежи · 2025—н.в. · 3
            кейса. Платёжные сценарии для бизнеса…» — без ответа на вопрос
            «чья». */}
        <span className="sr-only">{company.name}</span>
      </span>

      <span className="block">
        <span className="pf-caption pf-ink-soft pf-num block">{kicker}</span>

        {/* Заголовок карточки — само описание компании, разбитое надвое.
            Приглушение сделано прозрачностью чернил, а не вторым цветом:
            хроматики на странице нет вовсе.

            ─── ПОЧЕМУ 60 %, А НЕ 50 % ───────────────────────────────────────
            В образце стоит `primary/50`. Посчитано: `#171717` на белом при
            50 % даёт `#8b8b8b` и контраст 3.41:1. На широкой ширине фраза
            набрана кеглем 24 и проходит как крупный текст (порог 3:1), а на
            390 `.pf-h2` — это 20 px, где порог уже 4.5:1, и та же краска его
            не берёт. 60 % дают `#747474` и 4.67:1 на любом кегле. Машинная
            приёмка этого не видит: истории снимаются в 1280, где 24 px. */}
        {/* Максимум три строки: решение владельца 2026-08-03. Описания у трёх
            компаний разной длины (4 / 5 / 4 строки), и ряд из-за этого дышал
            неровно. Обрезка многоточием, а не сокращение текста: полное
            описание живёт на странице компании, править авторский текст нельзя. */}
        <span className="pf-h2 text-foreground mt-4 mb-5 block">
          {head}{" "}
          {tail ? (
            <span
              className="text-primary/60 group-hover:text-primary/80 font-medium transition-colors duration-500 ease-out"
              data-testid="pf-lede-tail"
            >
              {tail}
            </span>
          ) : null}
        </span>

      </span>

      <span className={`pf-ui inline-flex items-center gap-2 font-medium ${ROW_CELL_BODY}`}>
          Смотреть кейсы
          <MoveRight
            aria-hidden="true"
            className="size-4 transition-transform duration-500 ease-out group-hover:translate-x-1"
          />
      </span>
    </button>
  )
}
