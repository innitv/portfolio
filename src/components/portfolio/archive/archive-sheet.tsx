import * as React from "react"

import { AnimatePresence, motion } from "framer-motion"

import { DURATION, EASE, TIMING } from "@/components/portfolio/motion"

import type { ArchiveCompany } from "@/views/portfolio-archive.model"

/*
 * Вкладки списка кейсов. Две и жёстко: владелец 2026-08-27 просил разделить
 * обычные работы и сделанные с AI, а не завести произвольные разделы.
 *
 * Подписи строчными и моноширинной — как «← все работы» и строка отрасли на
 * этом же экране: вкладки служебные, и в один голос с именем компании они бы
 * спорили.
 */
type TabId = "all" | "ai"

/*
 * Нумерация строк СЧИТАЕТСЯ ПО МЕСТУ В СПИСКЕ, а не берётся из данных кейса.
 *
 * Владелец 2026-08-27: «нумерация кейсов в табе AI тоже начинается с единицы».
 * В данных номер сквозной по компании (у первых работ А3 это I-III, у AI-работ
 * IV-VI) — он принадлежит порядку кейсов компании, а не показанному списку.
 * Внутри вкладки счёт свой: человек видит три работы и ждёт I, II, III.
 *
 * Запас на шесть строк: у компании их сейчас максимум три на вкладку, а дальше
 * подставляется номер из данных — лучше сквозной, чем пустое место.
 */
const ROMAN = ["I", "II", "III", "IV", "V", "VI"]

const TABS: { id: TabId; label: string }[] = [
  { id: "all", label: "работы" },
  { id: "ai", label: "ai-работы" },
]

/**
 * Синий экран компании.
 *
 * ─── ПОЧЕМУ ПЛОСКОСТЬ СПУСКАЕТСЯ СВЕРХУ ─────────────────────────────────────
 * Экран приходит `clip-path`-ом сверху вниз и набирает ход: старт медленный,
 * середина быстрая. Выезд снизу пробовали — он читался как «всплыло окно», а
 * не как разлив цвета из полосы Archive, которая стоит наверху страницы.
 *
 * Содержимое приходит ПОСЛЕ плоскости, лесенкой: пока цвет ещё едет, текста на
 * нём нет. Отсюда задержка 0.38 с у первого элемента — она больше половины
 * длительности самой плоскости.
 *
 * ─── ЧТО ДОБАВЛЕНО К ПРОТОТИПУ ──────────────────────────────────────────────
 * Строки кейсов ведут на настоящие страницы кейсов сайта. В прототипе они были
 * немыми: данных там не было, вести было некуда. Кликабельная строка, которая
 * ничего не делает, — дефект, поэтому на живом сайте она получила адрес.
 *
 * Возврат: «← все работы», Esc и возврат фокуса на имя компании, с которого
 * экран открыли.
 *
 * ─── ПОЧЕМУ ЗДЕСЬ НЕТ ВЕТКИ prefers-reduced-motion ──────────────────────────
 * Раньше при `reduce` спуск заменялся на `duration: 0` — экран просто возникал.
 * На машине владельца эта настройка включена системно, и 2026-08-13 он увидел
 * ровно это: «пропали анимации на синих экранах». Промежуточный вариант —
 * кроссфейд вместо спуска — он тоже отклонил: «они просто появляются».
 *
 * Решение владельца: спуск плоскости остаётся всегда. Это осознанное отступление
 * от WCAG 2.3.3 — движение здесь и есть содержание экрана, а не украшение.
 * Смягчено тем, что движение одно, короткое (0.72 с), без параллакса и мигания,
 * и происходит только по прямому нажатию человека. Заезд болида — единственное
 * крупное перемещение — при заходе не запускается вовсе.
 */

/** Длительность спуска плоскости, секунды. Значение — в `motion.ts`. */
const SHEET_IN = DURATION.sheetIn

/**
 * Длительность ухода плоскости, секунды. Принято владельцем 2026-08-14.
 *
 * Было 0.4 «чтобы возврат не читался как второе событие», на кривой
 * `[0.4, 0, 1, 1]` — ease-IN, то есть с разгоном до последнего кадра и обрывом
 * на полном ходу. Замедление до темпа прихода владелец посмотрел и оставил:
 * «оставляй как есть сейчас».
 *
 * Возврат к именам компаний и занавес на страницу кейса идут одинаково — 0.72,
 * но это не одно решение на двоих: у занавеса своя история подбора
 * (`sheet-curtain.tsx`), и менять их надо порознь.
 */
const SHEET_OUT = DURATION.sheetOut

/** Пауза перед первым элементом содержимого, секунды. */
const ITEMS_DELAY = TIMING.itemsDelay

/** Шаг лесенки, секунды. */
const ITEMS_STAGGER = TIMING.itemsStagger

/** Длительность появления элемента, секунды. */
const ITEM_DURATION = DURATION.item

/*
 * Развёртка строки: закрыта — открыта.
 *
 * 🔴 НАПРАВЛЕНИЕ ОДНО НА ВЕСЬ САЙТ — СЛЕВА НАПРАВО. Сдвиг снизу (`y: 20`) снят
 * 14.09.2026: главная набирается квадратами слева направо, и строки синего
 * экрана, выезжавшие снизу, читались вторым жестом на том же экране.
 *
 * 🔴 РАЗВЁРТКА ИДЁТ МАСКОЙ, А НЕ `clip-path`, И ЭТО НЕ ВЫБОР ВКУСА. Клип у
 * содержимого уже занят: им лист обрезает строки по кромке плоскости на уходе
 * (`CONTENT_EXIT`), и вторая роль на том же свойстве ломала обе — проверки
 * «содержимое не переживает кромку плоскости» и «не появляется раньше
 * плоскости» упали разом. Маска свободна и складывается с клипом.
 */
const WIPE_SHUT = "0%"
const WIPE_OPEN = "100%"

const EASE_IN_SHEET = EASE.inSheet
/**
 * Кривая ухода — та же, что у занавеса на кейс, и по той же причине.
 *
 * Прежняя `[0.4, 0, 1, 1]` — это ease-IN: плоскость трогалась вяло и разгонялась
 * до самого конца, то есть обрывалась на полном ходу. Отсюда и ощущение рывка:
 * дело было не только в длительности, но и в том, что движение не имело
 * завершения.
 *
 * `[0.33, 1, 0.68, 1]` — ease-out: ответ на нажатие мгновенный, дальше мягкое
 * доезжание. Кривая уже принята владельцем на занавесе, поэтому здесь она не
 * подбирается заново.
 */
const EASE_OUT_SHEET = EASE.outSheet
const EASE_ITEM = EASE.item

/**
 * ─── СОДЕРЖИМОЕ УХОДИТ ТЕМ ЖЕ КЛИПОМ, ЧТО И ПЛОСКОСТЬ ───────────────────────
 *
 * Плоскость обрезается СНИЗУ ВВЕРХ, то есть низ листа освобождается первым:
 * кромка пролетает нижние 10 % высоты за ~50 мс на десктопе и за ~30 мс на
 * телефоне. Пока содержимое гасло общим fade по времени, величины внизу висели
 * на голых чернилах ещё треть секунды после того, как кобальт из-под них ушёл.
 * Владелец: «числа снизу уходят медленно, кобальт уже оттуда ушёл, а значения
 * всё ещё исчезают» (2026-08-14).
 *
 * Подбирать длительности по ярусам пробовали — тупик: на узком экране кромка
 * проходит низ за пару кадров, и никакое затухание по времени за ней не
 * успевает. Синхронность должна быть структурной, а не подогнанной: тот же
 * `clip-path`, та же кривая, та же длительность — тогда текст и цвет уходят
 * одной кромкой по определению, на любой высоте окна.
 *
 * 🔴 Клип задан КЛЮЧЕВЫМИ КАДРАМИ (`[OPEN, CLOSED]`), а не одним значением.
 * Так композитный слой возникает только на время ухода: всё остальное время
 * текст живёт вне слоя и рисуется субпиксельным сглаживанием. Ради этого слои и
 * разводили — разбор в шапке файла. На уходе имя не страдает: у `.pa-huge`
 * сглаживание зафиксировано в CSS, то есть переключаться режимам нечему.
 *
 * (Объявление ниже CLOSED/OPEN — оно ими и пользуется.)
 */
const CLOSED = "inset(0% 0% 100% 0%)"
const OPEN = "inset(0% 0% 0% 0%)"

const CONTENT_EXIT = {
  exit: {
    clipPath: [OPEN, CLOSED],
    transition: { duration: SHEET_OUT, ease: EASE_OUT_SHEET },
  },
}

export interface ArchiveSheetProps {
  company?: ArchiveCompany
  /**
   * Экран уже открыт при первом кадре — без спуска плоскости и без лесенки.
   *
   * 🔴 Нужен при заходе по адресу `/archive/<company>`, то есть при возврате со
   * страницы кейса. Спуск здесь означал бы, что плакат под ним виден все 0.72 с:
   * человек нажал «← все работы» и вместо работ компании успевает увидеть
   * главный экран (поймано владельцем 2026-08-14).
   *
   * Движение остаётся ровно там, где оно содержательно: при нажатии на имя
   * компании внутри `/archive`. Открытие по прямому адресу — не жест, а
   * состояние страницы, и анимировать его нечем.
   */
  instant?: boolean
  /**
   * Содержимое уже показано: ни спуска, ни лесенки — лист стоит готовым.
   *
   * 🔴 Нужен ровно в одном месте: под уходящим занавесом возврата. Там лесенку
   * уже отыграл сам занавес — это тот же лист, приехавший поверх кейса, — и
   * повторять её здесь значило бы моргнуть текстом на стыке.
   *
   * Во всех остальных случаях лесенка идёт: правило владельца «один и тот же
   * экран открывается одинаково, откуда бы ни пришли».
   */
  revealed?: boolean
  /** Спуск плоскости закончен — экран можно передавать маршруту. */
  onOpened?: () => void
  onClose: () => void
  onOpenCase?: (companyId: ArchiveCompany["id"], caseId: string) => void
}

export function ArchiveSheet({
  company,
  instant,
  revealed,
  onOpened,
  onClose,
  onOpenCase,
}: ArchiveSheetProps) {
  const backRef = React.useRef<HTMLButtonElement | null>(null)

  React.useEffect(() => {
    if (!company) return undefined

    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") onClose()
    }

    window.addEventListener("keydown", onKeyDown)
    // Фокус уезжает на экран вместе с содержимым: иначе после нажатия он
    // остаётся на имени компании, спрятанном под плоскостью.
    backRef.current?.focus()
    return () => window.removeEventListener("keydown", onKeyDown)
  }, [company, onClose])

  /**
   * Появление одного элемента содержимого. Задержка считается по месту в
   * общем порядке (имя, подпись, строки кейсов, величины) — ровно так же, как
   * в прототипе, где эти узлы шли одним плоским списком.
   */
  /*
    🔴 Лесенка содержимого идёт ВСЕГДА, даже когда плоскость уже открыта.

    Открытие экрана компании — это два движения подряд: приходит цвет, за ним
    лесенкой встаёт текст. Один и тот же экран обязан открываться одинаково,
    откуда бы ни пришли, — владелец поймал разницу дважды: «почему разные
    анимации» (2026-08-14) и «с главной текст быстро появляется, а с кейса
    медленно» (2026-08-15).

    Второй раз причина была в ОТСЧЁТЕ. С главной движения накладываются: цвет
    едет 0,72 с, текст идёт поверх него с 0,38 — и встаёт ровно к приходу
    плоскости (замер: имя на 741 мс). На возврате они шли подряд: сначала
    пустая плоскость закрывала кейс, и лишь потом стартовала лесенка — имя
    вставало на 1072 мс. Лечится не здесь, а в маршруте: теперь на возврате
    приезжает этот же лист целиком, со своим спуском и лесенкой, поэтому оба
    пути идут одним движением.

    `revealed` — единственное исключение: лист под уходящим занавесом уже
    отыграл своё и стоит готовым.
  */
  /*
    Активная вкладка списка кейсов. Сбрасывается на «работы» при смене
    компании: у следующей свой состав, и открывать её на пустой вкладке
    предыдущей нельзя.
  */
  const [tab, setTab] = React.useState<TabId>("all")
  /*
    Переключение вкладки — самостоятельное движение, не часть входа листа.

    Владелец 2026-08-27: «нужен более плавный переход между табами, допустим
    чтобы кейсы внутри появлялись так же, как простые работы». Лесенка та же,
    но БЕЗ паузы `ITEMS_DELAY`: та пауза ждёт, пока доедет плоскость экрана, а
    при смене вкладки плоскость уже стоит — и полсекунды пустоты читались бы
    зависанием.
  */
  const [switching, setSwitching] = React.useState(false)

  React.useEffect(() => {
    setTab("all")
    setSwitching(false)
  }, [company?.id])

  const openTab = (next: TabId) => {
    if (next === tab) return
    setSwitching(true)
    setTab(next)
  }

  const caseGroups = React.useMemo(() => {
    const all = company?.cases ?? []
    if (!company?.caseTabs) return { ai: [], all }
    return {
      ai: all.filter((study) => study.ai),
      all: all.filter((study) => !study.ai),
    }
  }, [company?.caseTabs, company?.cases])

  const shownCases = tab === "ai" ? caseGroups.ai : caseGroups.all

  /*
    Высота списка держится по САМОЙ ДЛИННОЙ вкладке, а не по показанной.
    Владелец: «контейнер такой же пускай будет по величине у таба ai-работы».
    Иначе при переключении низ экрана — величины компании — прыгает вверх.

    🔴 Недостающие строки добираются ЗАПОЛНИТЕЛЯМИ, а не формулой высоты.
    Прежняя редакция ставила `min-block-size: строки × 56px`, где 56 — тач-цель
    строки, а не её рост: заголовок набран `clamp(20px, 2.3vw, 32px)`, и на 1440
    строка занимает 76. Список работ выходил 229 px против расчётных 168, и при
    переключении вкладки величины компании прыгали вверх на 61 px.
  */
  /*
    Слои списка: при вкладках рендерятся обе группы, при их отсутствии — одна.
    Порядок фиксирован, чтобы ключи не переезжали между перерисовками.
  */
  const caseLayers = company?.caseTabs
    ? ([
        { id: "all", cases: caseGroups.all },
        { id: "ai", cases: caseGroups.ai },
      ] as const)
    : ([{ id: "all", cases: caseGroups.all }] as const)

  /*
    Появление строки кейса. При входе листа — общая лесенка (кейсы идут третьими
    после шапки и вкладок), при переключении вкладки — та же лесенка, но сразу:
    ждать нечего, плоскость уже на месте.
  */
  const caseItem = (index: number) => {
    if (!switching) return item(3 + index)

    return {
      animate: { opacity: 1, ["--pa-wipe" as string]: WIPE_OPEN },
      initial: { opacity: 0, ["--pa-wipe" as string]: WIPE_SHUT },
      style: { ["--pa-wipe" as string]: WIPE_SHUT },
      transition: {
        delay: index * ITEMS_STAGGER,
        duration: ITEM_DURATION,
        ease: EASE_ITEM,
      },
    }
  }

  const item = (index: number, shift = true) => {
    if (revealed) {
      return {
        animate: { opacity: 1, ["--pa-wipe" as string]: WIPE_OPEN },
        initial: { opacity: 1, ["--pa-wipe" as string]: WIPE_OPEN },
      }
    }

    const delay = (instant ? 0 : ITEMS_DELAY) + index * ITEMS_STAGGER

    return {
      /*
       * 🔴 Непрозрачность стартует с нуля У ВСЕХ строк, даже у тех, что идут
       * без развёртки. Первый заход давал таким строкам `opacity: 1` сразу, и
       * проверка «содержимое не появляется раньше плоскости» поймала кнопку
       * возврата: она была видна ещё до того, как лист приехал.
       */
      animate: { opacity: 1, ["--pa-wipe" as string]: WIPE_OPEN },
      initial: { opacity: 0, ["--pa-wipe" as string]: shift ? WIPE_SHUT : WIPE_OPEN },
      style: { ["--pa-wipe" as string]: shift ? WIPE_SHUT : WIPE_OPEN },
      transition: {
        delay,
        duration: ITEM_DURATION,
        ease: EASE_ITEM,
      },
    }
  }

  return (
    <AnimatePresence>
      {company ? (
        <section
          aria-label={company.wordmark}
          className="pa-sheet"
          data-testid="pa-sheet"
          key={company.id}
        >
          {/*
            ─── ПЛОСКОСТЬ ЕДЕТ ОТДЕЛЬНО ОТ ТЕКСТА ──────────────────────────
            Анимируется ТОЛЬКО цвет — пустой слой без содержимого. Текст лежит
            рядом, в обычном потоке, и в композитный слой не попадает вовсе.

            Раньше `clip-path` стоял на всём листе, и текст неизбежно оказывался
            внутри анимируемого слоя: там он рисуется без субпиксельного
            сглаживания и выглядит обведённым. Первый заход лечил последствие —
            снимал слой после прихода, — но всё время движения заголовок был
            мутным. Разделение убирает причину: рендер одинаково чёткий на
            любом кадре.

            Скрывать текст на время проезда больше не нужно клипом: он и так
            приходит позже плоскости, прозрачностью (`ITEMS_DELAY`).
          */}
          <motion.div
            animate={{ clipPath: OPEN }}
            aria-hidden="true"
            className="pa-sheet-plane"
            data-testid="pa-sheet-plane"
            exit={{
              clipPath: CLOSED,
              // Уход в темпе прихода и с мягким завершением — см. SHEET_OUT.
              transition: { duration: SHEET_OUT, ease: EASE_OUT_SHEET },
            }}
            /*
              🔴 При заходе по адресу плоскость открыта С ПЕРВОГО КАДРА.

              Спуск отсюда занимал 0.72 с, и всё это время под ним был виден
              плакат: человек нажимал «← все работы» на кейсе и успевал увидеть
              главный экран вместо работ компании.
            */
            initial={{ clipPath: instant ? OPEN : CLOSED }}
            onAnimationComplete={onOpened}
            transition={instant ? { duration: 0 } : { duration: SHEET_IN, ease: EASE_IN_SHEET }}
          />

          {/*
            Содержимое уходит той же кромкой, что и цвет под ним, — см.
            CONTENT_EXIT. Общий fade по времени как раз и оставлял величины
            висеть внизу на голых чернилах.
          */}
          <motion.div className="pa-sheet-inner" {...CONTENT_EXIT}>
          <div className="pa-sheet-head">
            {/*
              Кнопка возврата — тоже содержимое, и приходит вместе с именем, а
              не раньше плоскости.

              До разделения слоёв её прятал общий `clip-path`: элементы без
              собственной анимации были не видны просто потому, что лист был
              обрезан целиком. Как только текст вынесли из анимируемого слоя,
              всё неанимированное стало проступать на чернилах с нулевого кадра
              — кнопка висела на тёмном фоне, пока кобальт ещё ехал вниз
              (поймано владельцем 2026-08-14).

              Без сдвига, как и имя: строка служебная и стоит на одном уровне с
              «портфолио · 2026» на главном экране — прыжок по вертикали здесь
              читался бы как расхождение шапок.
            */}
            <motion.button
              className="pa-back"
              data-testid="pa-back"
              onClick={onClose}
              ref={backRef}
              type="button"
              {...item(0, false)}
            >
              ← все работы
            </motion.button>
            {/*
              Имя проявляется прозрачностью, но БЕЗ сдвига — и с заранее
              зафиксированным сглаживанием (см. `.pa-huge` в CSS).

              Сдвиг убран потому, что ставил буквы кегля 215 на дробные позиции
              и они дрожали. Прозрачность оставлена: плавность нужна, а разницы
              в толщине больше нет — сглаживание не переключается.
            */}
            <motion.div className="pa-huge" {...item(0, false)}>
              {company.wordmark}
            </motion.div>
            <motion.div className="pa-sub" {...item(1)}>
              {company.meta}
            </motion.div>
          </div>

          {/*
            ─── ВКЛАДКИ «РАБОТЫ» И «AI-РАБОТЫ» ─────────────────────────────
            Правка владельца 2026-08-27. Стоят только там, где компания их
            включила (`caseTabs`): просили их на А3, и у остальных экран
            остаётся прежним.

            Разметка — роли `tablist`/`tab`, а не просто кнопки: список под
            ними меняется целиком, и без ролей человек с экранным диктором
            не узнает, что переключил содержимое, а не открыл новый экран.
          */}
          {/*
            Вкладки и список — ОДИН блок в раскладке листа: `.pa-sheet-inner`
            распределяет детей `space-between`, и отдельной строкой вкладки
            получали свою долю пустоты — 175 px между ними и первой работой.
          */}
          <div className="pa-cases-block">
          {company.caseTabs ? (
            <motion.div
              aria-label="Разделы работ"
              className="pa-tabs"
              data-testid="pa-tabs"
              role="tablist"
              {...item(2, false)}
            >
              {TABS.map((entry) => (
                <button
                  aria-selected={tab === entry.id}
                  className="pa-tab"
                  data-active={tab === entry.id}
                  data-testid={`pa-tab-${entry.id}`}
                  key={entry.id}
                  onClick={() => openTab(entry.id)}
                  role="tab"
                  type="button"
                >
                  {entry.label}
                </button>
              ))}
            </motion.div>
          ) : null}

          <div
            className="pa-cases"
            data-testid="pa-cases"
            role={company.caseTabs ? "tabpanel" : undefined}
          >
            {caseLayers.map((layer) => {
              const active = layer.id === tab

              return (
                <div
                  /*
                    Неактивная вкладка остаётся в разметке и держит высоту, но из
                    чтения, наведения и табуляции выключена: `visibility` снимает
                    её и для диктора, и для мыши, и для клавиатуры.
                  */
                  aria-hidden={active ? undefined : true}
                  className="pa-cases-layer"
                  data-active={active}
                  key={layer.id}
                >
                  {layer.cases.map((study, index) => (
                    <motion.button
                      className="pa-case"
                      data-testid={`pa-case-${study.caseId}`}
                      /*
                        Ключ с вкладкой: без него framer-motion считает строки
                        одним и тем же узлом и просто подменяет в них текст —
                        лесенка при переключении не проигрывается вовсе.
                      */
                      key={`${tab}-${study.caseId}`}
                      onClick={() => onOpenCase?.(company.id, study.caseId)}
                      tabIndex={active ? undefined : -1}
                      type="button"
                      {...(active ? caseItem(index) : {})}
                    >
                      <span className="pa-case-index">{ROMAN[index] ?? study.index}</span>
                      <span className="pa-case-title">{study.title}</span>
                      <span className="pa-case-impact">{study.impact}</span>
                    </motion.button>
                  ))}
                  {/*
                    Пустая вкладка говорит словами, а не пустотой: без строки
                    экран выглядел бы сломанным переключателем.
                  */}
                  {layer.cases.length === 0 ? (
                    <motion.p
                      className="pa-cases-empty"
                      data-testid={active ? "pa-cases-empty" : undefined}
                      key={`${tab}-empty`}
                      {...(active ? caseItem(0) : {})}
                    >
                      Работы с AI появятся здесь
                    </motion.p>
                  ) : null}
                </div>
              )
            })}
          </div>
          </div>

          <div className="pa-facts">
            {company.facts.map((fact, index) => (
              <motion.div
                key={`${fact.value}-${fact.caption}`}
                {...item(2 + company.cases.length + index)}
              >
                <div className="pa-fact-value">{fact.value}</div>
                <div className="pa-fact-caption">{fact.caption}</div>
              </motion.div>
            ))}
          </div>
          </motion.div>
        </section>
      ) : null}
    </AnimatePresence>
  )
}
