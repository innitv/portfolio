import * as React from "react";

import { motion } from "framer-motion";

import { DURATION as MOTION, EASE } from "@/components/portfolio/motion";

/**
 * Уход синего экрана компании при переходе на кейс.
 *
 * ─── ЗАЧЕМ ОТДЕЛЬНЫЙ КОМПОНЕНТ ──────────────────────────────────────────────
 * Синий экран живёт внутри `/archive`, а страница кейса — другой маршрут. При
 * переходе `/archive` размонтируется целиком, и анимировать в нём уже нечего:
 * экран просто пропадал, а кейс появлялся вспышкой.
 *
 * Занавес рендерится НАД новым маршрутом, поэтому под уезжающей плоскостью
 * сразу виден кейс — ровно то, что и требуется: синий закрывается, а под ним
 * уже открытая работа.
 *
 * ─── ДВИЖЕНИЕ ───────────────────────────────────────────────────────────────
 * Обратное открытию: плоскость приходила сверху вниз (`inset(0 0 100% 0)` →
 * `0`), уходит — снизу вверх, освобождая экран. Кривая разгонная: уход не
 * должен читаться как второе событие после нажатия.
 */

/**
 * Длительность ухода, секунды.
 *
 * История правок здесь — про то, что «быстро» и «резко» человек называет одним
 * словом, а лечатся они по-разному:
 *
 * 1. 0.52 — «слишком быстро закрывается, надо чтобы с такой же скоростью
 *    уходил». Подняли до 0.72, в темп прихода синего экрана.
 * 2. 0.72 — «как-то резко уходит» (2026-08-14). Пробовали растянуть до 1.0 —
 *    не помогло, и это оказалось диагнозом: дело было не в длительности, а в
 *    распределении хода (см. EASE_OUT).
 *
 * Итог — 0.72, то есть **ровно длительность открытия синего экрана**
 * (`SHEET_IN` в `archive-sheet.tsx`). Решение владельца: занавес должен идти
 * так же, как открытие, только другим графиком — движение обратное.
 *
 * Замер подтверждает совпадение темпа: у открытия половина пути к 240 мс и
 * 90 % к 445, у ухода — 240 и 450. Расходятся только первые 150 мс, и это
 * намеренно: уход отвечает на нажатие и не имеет права медлить.
 */
const DURATION = MOTION.curtain;

const OPEN = "inset(0% 0% 0% 0%)";
const CLOSED = "inset(0% 0% 100% 0%)";

/**
 * Кривая ухода — та же дуга, что у открытия, но своим графиком.
 *
 * Решение владельца 2026-08-14: занавес должен идти как открытие синего экрана,
 * «только другой график, раз это в обратную сторону». Длительность взята его же
 * (`SHEET_IN` = 0.72), а распределение хода подобрано так, чтобы совпали
 * середина и завершение, но начало отвечало на нажатие:
 *
 * | момент | открытие `[.4,0,.15,1]` | уход `[.4,.3,.3,1]` |
 * |--------|------------------------|---------------------|
 * | 100 мс |  6 %                   | 14 %                |
 * | 240 мс | 50 %                   | 50 %                |
 * | 445 мс | 90 %                   | 90 %                |
 *
 * То есть это НЕ зеркало и не копия: копия медлит с ответом, зеркало срывается
 * рывком (оба промаха ниже), а здесь совпадает то, что человек считывает как
 * «тот же темп», и расходится только первая треть секунды.
 *
 * ─── ДВА ПРОМАХА ДО НЕГО, ОБА ПОЙМАНЫ ЗАМЕРОМ ───────────────────────────────
 * 1. Сначала сюда скопировали кривую ПРИХОДА `[0.4, 0, 0.15, 1]`. Для прихода
 *    она верна — плоскость набирает ход, — но на уходе это значит, что экран
 *    медлит с ответом на нажатие: за первые 110 мс проходило 4.7 % пути.
 * 2. Затем взяли её зеркало по контрольным точкам, `[0.85, 0, 0.6, 1]`.
 *    Арифметика зеркала верна, результат — хуже прежнего: при `x1 = 0.85`
 *    кривая почти до конца держится у нуля, и за 360 мс проходило 15 %, после
 *    чего срывалась рывком.
 *
 * Вывод на будущее: кривую проверять замером на кадрах, а не выводить из
 * формулы. Контрольные точки не читаются глазами.
 *
 * ─── СТАРТ СМЯГЧАЛСЯ ДВАЖДЫ ─────────────────────────────────────────────────
 * 3. Экспо-кривая `[0.16, 1, 0.3, 1]` уносила плоскость на 51 % за первые
 *    100 мс — ответ мгновенный, но рывком. Взяли более пологую
 *    `[0.33, 1, 0.68, 1]`.
 * 4. Она же оказалась «как-то резко» (2026-08-14). Замер объяснил, почему одной
 *    длительности не хватило: у экспо-кривой ВЕСЬ ход в начале, а конец —
 *    мёртвый хвост. При 1.0 с профиль был 27 % за 100 мс, половина пути к
 *    210 мс и последние 10 % за 455 мс — то есть рывок, а потом полсекунды
 *    почти неподвижного занавеса. Растягивать такую кривую бесполезно:
 *    удлиняется ровно та часть, которой не видно.
 *
 * `[0.4, 0.3, 0.3, 1]` распределяет ход ровнее и на 0.72 с ложится в темп
 * открытия — таблица выше.
 *
 * Кривые здесь подбирались ТОЛЬКО расчётом профиля и замером на кадрах — по
 * контрольным точкам разницу между этими тремя вариантами не увидеть.
 */
const EASE_OUT = EASE.curtainOut;

/**
 * ─── ЗАНАВЕС ХОДИТ В ОБЕ СТОРОНЫ ────────────────────────────────────────────
 * `out` — уход на кейс: плоскость компании уезжает вверх, под ней уже открыта
 * работа. `in` — возврат с кейса: плоскость приходит сверху вниз и накрывает
 * страницу кейса, а под ней открывается экран компании.
 *
 * Приход появился 2026-08-14 по замечанию владельца «анимацию не забудь
 * перенести»: возврат к работам был мгновенной подменой страницы, хотя дорога
 * туда — движение. Жест обязан читаться в обе стороны, иначе назад ведёт не
 * тот же путь, которым пришли.
 *
 * Кривая прихода — та же, что у синего экрана внутри `/archive`
 * (`EASE_IN_SHEET` в `archive-sheet.tsx`): медленный старт с разгоном, как
 * будто цвет разливается из полосы наверху. Длительность общая, 0.72.
 */
const EASE_IN = EASE.inSheet;

export interface SheetCurtainProps {
  /**
   * Направление. `out` — уход на кейс (по умолчанию), `in` — возврат к работам.
   */
  direction?: "in" | "out";
  /** Имя компании — то же слово, что стояло на синем экране. */
  wordmark: string;
  onDone: () => void;
}

export function SheetCurtain({ direction = "out", wordmark, onDone }: SheetCurtainProps) {
  const coming = direction === "in";

  return (
    <motion.div
      animate={{ clipPath: coming ? OPEN : CLOSED }}
      aria-hidden="true"
      className="pa-curtain"
      data-direction={direction}
      data-testid="pa-curtain"
      initial={{ clipPath: coming ? CLOSED : OPEN }}
      onAnimationComplete={onDone}
      transition={{ duration: DURATION, ease: coming ? EASE_IN : EASE_OUT }}
    >
      {/*
        Имя едет с плоскостью только на УХОДЕ: там оно остаётся от экрана,
        который закрывается, и без него уезжал бы пустой прямоугольник.

        🔴 На приходе имени здесь НЕТ. Экран компании открывается лесенкой —
        сначала цвет, потом текст, — и имя приходит вместе с остальным
        содержимым уже на самом экране. Покажи его на занавесе, и оно
        появилось бы дважды: сначала на плоскости, потом ещё раз в лесенке.
      */}
      {coming ? null : <div className="pa-curtain-word">{wordmark}</div>}
    </motion.div>
  );
}
