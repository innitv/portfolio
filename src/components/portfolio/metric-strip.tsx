import { cn } from "@/lib/utils"

import type { CaseMetric } from "@/views/portfolio.data"

/**
 * Сетка метрик: крупное число, подпись под ним.
 *
 * Раскладка из блока `@shadcnblocks/case-study1`: `grid-cols-2` на узкой
 * ширине, четыре колонки на широкой, зазор 20. Карточек нет — карточка
 * подняла бы число на третий уровень глубины, которого на сайте нет.
 *
 * ─── ЧЕТЫРЕ КОЛОНКИ С `xl`, А НЕ С `lg` КАК В БЛОКЕ ─────────────────────────
 * На 1024 левая колонка страницы кейса ужимается с 692 до 585, ячейка из
 * четырёх становится 131 px, и «15–25%» ломается по тире на две строки:
 * «15–» / «25%». Разрыв по тире — законная точка переноса, запретить её,
 * не запретив перенос вовсе, нельзя, а «10–15 пунктов» переносится обязана.
 * Поэтому четыре колонки включаются там, где ячейка снова 158 px, — с 1280.
 * Найдено просмотром страницы на 1024, машинная приёмка молчала.
 *
 * Ни одно число здесь не сочинено: `value` — подстрока предложения из тела
 * кейса (`caseMetrics` в `portfolio.data.ts`), `label` — метка до двоеточия из
 * того же предложения. Полное предложение при этом остаётся на своём месте в
 * разделе «Метрики успеха»: наверху сводка, в разделе — описание действия.
 * Метрика без числа в сетку не попадает — правило `supabase.com` «нет
 * значения, нет строки».
 *
 * ─── ПОЧЕМУ 30/36, А НЕ 36/48 КАК В БЛОКЕ ───────────────────────────────────
 * У блока значение набрано `text-4xl sm:text-5xl`. Наши значения длиннее
 * односложных «19%»: «10–15 пунктов» — тринадцать знаков. В колонке 158 px
 * (левая колонка 692 при четырёх ячейках и зазоре 20) кегль 48 рвёт такое
 * значение на три строки, 36 — на две. Поэтому взяты две верхние ступени
 * собственной шкалы сайта, 30 и 36; ступени 48 в ней нет вовсе.
 *
 * ─── ПОЧЕМУ SUBGRID, А НЕ ПРОСТО КОЛОНКА ────────────────────────────────────
 * «10–15 пунктов» переносится на две строки даже в 36 — и в обычной
 * `flex flex-col` подпись этой ячейки уезжала на 40 px ниже соседних, ряд
 * подписей превращался в ступеньку (замерено на кейсе «Редизайн главной»:
 * labelY 286/286/286/326). `grid-rows-subgrid` кладёт значение и подпись в
 * ОБЩИЕ для ряда дорожки, поэтому подписи стоят на одной линии независимо от
 * числа строк в числе.
 */

/**
 * Стрелка «до → после» набирается мельче самих чисел.
 *
 * ─── ЗАМЕР, ИЗ КОТОРОГО ЭТО СЛЕДУЕТ ─────────────────────────────────────────
 * У кейса «Услуги Web» все три значения имеют вид «3% → 7%», и каждое ломалось
 * на две строки: «3% →» / «7%». Ячейка ряда — 158 px, а значению для одной
 * строки нужно было 164 px. Не хватало ШЕСТИ пикселей.
 *
 * Причина не в длине числа, а в том, что связка набиралась кеглем 36 наравне
 * с числами: у стрелки в этом кегле ширина глифа плюс два пробела съедали
 * почти четверть ячейки. Типографически она и не должна весить как число —
 * это знак отношения между ними, а не величина.
 *
 * Поэтому стрелка получает 0.55em и приглушённый тон. Числа не трогаются:
 * `value` остаётся дословной подстрокой предложения из тела кейса, меняется
 * только начертание связки внутри него.
 */
function MetricValue({ value }: { value: string }) {
  const parts = value.split(" → ")
  if (parts.length !== 2) return <>{value}</>

  return (
    <>
      {parts[0]}
      {/* `leading-none` обязателен: без него мелкий глиф со своим
          межстрочным добавлял 3 px к строке ЭТОГО значения, и в ряду с
          соседями без стрелки («4,6 из 5» — 40 px против 43) числа снова
          вставали на разные линии. Замерено на кейсе «Подписки». */}
      <span aria-hidden="true" className="pf-ink-soft mx-1 align-middle text-[0.55em] leading-none">
        →
      </span>
      {/* Стрелка скрыта от скринридера как декорация начертания, поэтому
          отношение проговаривается словом — иначе «3% 7%» звучит как два
          несвязанных числа. */}
      <span className="sr-only"> до </span>
      {parts[1]}
    </>
  )
}

export interface MetricStripProps {
  className?: string
  metrics: CaseMetric[]
}

export function MetricStrip({ className, metrics }: MetricStripProps) {
  if (metrics.length === 0) return null

  return (
    <dl
      className={cn(
        "grid grid-cols-2 gap-x-8 gap-y-5",
        /* Колонок ровно столько, сколько метрик, — тот же приём, что у ряда
           карточек на странице компании. Раньше здесь всегда стояли четыре, и
           при трёх метриках они жались в 158 px слева, оставляя пустой
           четвёртую колонку: числа читались слипшимися, а ряд — обрубленным.
           При трёх колонках ячейка становится 209 px. Заметил владелец. */
        metrics.length === 3 && "xl:grid-cols-3",
        metrics.length >= 4 && "xl:grid-cols-4",
        className
      )}
      data-testid="pf-metric-strip"
    >
      {metrics.map((metric) => (
        <div
          className="row-span-2 grid min-w-0 grid-rows-subgrid gap-2"
          key={`${metric.label}-${metric.value}`}
        >
          {/* Значение прижато к низу своей дорожки: дорожка высотой в самое
              длинное число ряда, и без этого односложные «15–25%» висели бы в
              40 px над собственной подписью. */}
          <dt className="pf-metric pf-num text-foreground self-end">
            <MetricValue value={metric.value} />
          </dt>
          <dd className="pf-caption pf-ink-soft">{metric.label}</dd>
        </div>
      ))}
    </dl>
  )
}
