/**
 * ─── ВОПРОСЫ БРИФА ─────────────────────────────────────────────────────────
 *
 * Тексты живут здесь, а не в компоненте — по тому же правилу, что и тексты
 * кейсов: формулировка вопроса важнее разметки поля, и править её надо в одном
 * месте.
 *
 * Состав и порядок сверены с брифами студий, которые публикуют свои опросники:
 * Mule Design (Mike Monteiro, 15 вопросов), Бюро Горбунова (39), Нимакс (28),
 * Live Typing (22), AGIMA (3), Сибирикс (5), плюс вопросники интервью со
 * стороной заказчика у NN/g и Kevin Hoffman. Ниже — только те решения, за
 * которыми стоит разбор, а не вкус.
 *
 * 🔴 ПРИНЦИП ОТБОРА: вопрос остаётся, только если ответ МЕНЯЕТ мой ответ
 * клиенту. «Опишите вашу целевую аудиторию» и «какие сайты вам нравятся» в
 * таком виде сюда не попали: на первый отвечают выдумкой («профессионалы
 * 25–45»), на второй вкусовщиной, и ни то ни другое не меняет ни срок, ни
 * цену, ни состав работ.
 *
 * 🔴 СПРАШИВАЕМ ПРО ПРОШЛОЕ, А НЕ ПРО ПЛАНЫ. «Что вы делали, когда это
 * понадобилось в прошлый раз» даёт факт; «как вы планируете это использовать»
 * даёт фантазию, которую потом нечем проверить.
 *
 * 🔴 ОБЯЗАТЕЛЬНЫХ ПОЛЕЙ ДВА: имя и одна строка о задаче. Принудительный вопрос
 * даёт либо уход, либо выдуманный ответ, который потом дороже разбирать, чем
 * отсутствующий (question protocol GOV.UK, Nielsen 2025, Baymard: при пометке
 * только необязательных полей 32 % людей получали ошибку валидации).
 *
 * 🔴 ПОЧТА СРЕДИ НИХ НЕ ЧИСЛИТСЯ — решение владельца 02.11.2026. Это
 * отступление от выборки: у Бюро Горбунова из 39 вопросов обязателен ровно
 * один email, у Viget обязательны три контактных поля. Довод против
 * принуждения сильнее: человек, который не хочет оставлять почту, впишет
 * выдуманную, и тогда потерян не контакт, а сам факт обращения — выдуманный
 * адрес неотличим от настоящего до первого отбитого письма. Способ связи при
 * этом нужен, поэтому пояснение у поля прямо отправляет за телеграмом.
 *
 * 🔴 СРОК И ДЕНЬГИ НЕ ОБЯЗАТЕЛЬНЫ, хотя и спрашиваются. Единственные в выборке,
 * кто сделал бюджет обязательным, — 10up, и они же единственные, кто объяснил
 * это прямо в тексте ошибки. Замеров «обязательное против необязательного поля
 * бюджета» не существует ни у одного источника, поэтому выбрана сторона, где
 * цена ошибки меньше: пустая графа честнее придуманной суммы.
 *
 * 🔴 ДВА РЕЖИМА ПОДАЧИ — приём AGIMA: «ответить по пунктам» или «написать
 * своими словами». Он снимает спор, который в отрасли не решён: Red Collar
 * считает высланный на самозаполнение бриф ошибкой номер один («напоминает
 * жуткий бюрократический документ»), Сибирикс прямо пишет, что онлайн-бриф у
 * них не заполняли вовсе, а Бюро и Нимакс требуют письменных ответов ДО
 * встречи. Правы обе стороны — для разных людей; выбирать, кто держит ручку,
 * оставлено человеку, а не мне.
 */

export type BriefFieldKind = "text" | "long" | "email" | "tel" | "url" | "choice" | "multi"

/** Как человек предпочитает отвечать. */
export type BriefMode = "points" | "free"

export interface BriefField {
  /** Короткое имя поля в письме и в записи ответа. */
  id: string
  /** Сам вопрос. Он же метка поля — плейсхолдеров вместо меток здесь нет. */
  question: string
  /** Пояснение под вопросом: зачем спрашиваю и что считается ответом. */
  hint?: string
  kind: BriefFieldKind
  /** Варианты для `choice` и `multi`. */
  options?: string[]
  required?: true
  /** Поле показывается только для этого рода задачи. */
  only?: "site" | "product"
}

export interface BriefSection {
  id: string
  title: string
  /** Вводка раздела: что здесь спрашивают и почему. */
  lede?: string
  /** Раздел виден только в этом режиме подачи. Без него — виден всегда. */
  mode?: BriefMode
  fields: BriefField[]
}

