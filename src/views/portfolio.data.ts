/*
 * ─── ЧИСЛО НЕ ЗАХВАТЫВАЕТ ТОЧКУ ПРЕДЛОЖЕНИЯ ─────────────────────────────────
 * Дробная часть записана как `[.,]\d+`, а не `[.,]?\d*`: второй вариант
 * позволял разделителю стоять БЕЗ цифр после него, и из «NPS вырос с 62 до
 * 74.» поднималось значение «62 → 74.» — с точкой предложения внутри числа.
 * На кегле 36 эта точка читается как опечатка. Найдено просмотром страницы
 * кейса «Подписки».
 */

/** `с 3% до 7%` → две величины: у автора этот формат уже есть в `impact`. */
const RANGE = /с\s+(\d+(?:[.,]\d+)?\s*%?)\s+до\s+(\d+(?:[.,]\d+)?\s*%?)/
/**
 * Одиночная величина: `15–25%`, `18 п.п.`, `10–15 пунктов`, `4,6 из 5`,
 * `20–35 секунд`, `2,5–3,5 минуты`, `0 дней`.
 *
 * 🔴 Единицы ВРЕМЕНИ заведены 2026-08-26, и без них блок цифр врал.
 *
 * У «Оптимизации флоу» результат измерен не в процентах, а в секундах и
 * минутах («вход сокращается до 20–35 секунд»). Разбор их не узнавал, величин у
 * кейса выходило ноль — и каркас честно ставил на позицию цифр рыбу шаблона.
 * На странице про регистрацию поставщика стояли Activation, Time to Action и
 * CES дашборда: числа настоящие, но от другого кейса.
 *
 * Пересчёта это правило не вводит: величина по-прежнему обязана быть подстрокой
 * авторской фразы. Расширен только список единиц, которые считаются величиной.
 */
const SINGLE =
  /(\d+(?:[.,]\d+)?(?:\s*[–—-]\s*\d+(?:[.,]\d+)?)?\s*(?:%|п\.п\.|пунктов|пункта|пункт|секунд(?:а|ы|у)?|минут(?:а|ы|у)?|дн(?:ей|я|ь)|пол(?:ей|я|е)|шаг(?:ов|а)?|из \d+))/

/**
 * Точка в конце предложения снимается, точка сокращения — нет.
 *
 * Прежнее безусловное `replace(/\.$/)` превращало «…выросла на 18 п.п.» в
 * «…выросла на 18 п.п» — то есть портило сокращение автора.
 */
function withoutTrailingPeriod(text: string): string {
  return /\.\p{L}\.$/u.test(text) ? text : text.replace(/\.$/, "")
}

/**
 * Единица измерения величины: всё, что стоит после последней цифры.
 *
 * `15–25%` → `%`, `10–15 пунктов` → `пунктов`, `с 3% до 7%` → `%`.
 */
function unitOf(value: string): string {
  return (/\d[^\d]*$/.exec(value)?.[0].replace(/^\d/, "") ?? "").trim().toLowerCase()
}

/**
 * Ряд метрик держит ОДНУ единицу измерения.
 *
 * Правило родственно запрету смешивать источники выше и введено по той же
 * причине — рядом не должны стоять величины разной природы. Замер, на котором
 * оно появилось (кейс «Редизайн главной», 2026-08-03): три метрики в
 * процентах и четвёртая «10–15 пунктов». Слово не помещалось в колонку 230 px,
 * переносилось второй строкой и поднимало число на 40 px над соседями — ряд
 * из четырёх чисел стоял на двух разных линиях. Но дело не только в вёрстке:
 * голое «10–15» рядом с процентами читается как проценты, а это неверно.
 *
 * Поэтому лишняя единица не подписывается мельче и не переносится — метрика
 * просто не поднимается в шапку. Она никуда не пропадает: полная фраза
 * остаётся в своём разделе тела кейса, откуда её сюда и подняли.
 *
 * Преобладающая единица считается по частоте; при равенстве побеждает единица
 * первой метрики, то есть порядок автора.
 */
function sameUnit(metrics: CaseMetric[]): CaseMetric[] {
  if (metrics.length < 2) return metrics

  const counts = new Map<string, number>()
  for (const metric of metrics) {
    const unit = unitOf(metric.value)
    counts.set(unit, (counts.get(unit) ?? 0) + 1)
  }

  const leader = unitOf(metrics[0].value)
  let winner = leader
  for (const [unit, count] of counts) {
    if (count > (counts.get(winner) ?? 0)) winner = unit
  }

  return metrics.filter((metric) => unitOf(metric.value) === winner)
}

/**
 * Величина кейса для блока крупных цифр.
 *
 * 🔴 Число и единица разведены НЕ ради красоты. При общем кегле «10–15 пунктов»
 * ломается на две строки и поднимает соседей по ряду — замер на 1920 и 1440
 * (2026-08-17). Это тот же дефект, из-за которого `sameUnit` вообще выбрасывает
 * чужую единицу из полосы на синем экране. Здесь он лечится типографикой:
 * единица идёт мельче в той же строке, поэтому и «%» и «пунктов» встают рядом с
 * числом, а ряд остаётся на одной линии.
 */
export interface CaseOutcome {
  amount: string
  label: string
  note: string
  unit: string
  value: string
}

/**
 * Величины раздела «Метрики успеха» для блока КРУПНЫХ ЦИФР на странице кейса.
 *
 * Заведено 2026-08-17 по правке владельца: «после блока с продуктовыми
 * гипотезами хочу блок с крупными цифрами с результатами».
 *
 * 🔴 Отличий от `caseMetrics` ровно два, и оба намеренные:
 *
 * 1. **Единицы НЕ приводятся к одной.** `sameUnit` выбрасывает «10–15 пунктов»
 *    рядом с процентами, и на синем экране это правильно: там колонка 230 px и
 *    единица не подписана, поэтому голое «10–15» читалось бы как проценты. Здесь
 *    единица стоит в самом значении и колонка втрое шире — обе причины отпадают,
 *    а выброшенная метрика CES унесла бы с собой четверть содержания блока.
 * 2. **Сохраняется НАПРАВЛЕНИЕ.** «35–45%» без глагола читается как рост, хотя в
 *    тексте это сокращение времени. Поэтому `note` — фраза автора с глаголом, из
 *    которой убрана только сама величина, чтобы число не звучало дважды.
 *
 * Ни одна цифра не сочиняется: `value` и `note` — подстроки его предложения.
 */
export function caseOutcomes(caseStudy: CaseStudy): {
  items: CaseOutcome[]
  title: string
} | null {
  /*
   * 🔴 Раздел ищется по тому же списку `METRIC_SECTION_TITLES`, что у полосы
   * величин, а не по одной метке «Метрики успеха».
   *
   * Причина — правка владельца 2026-08-17: «используй кейс А3 редизайн главной
   * как шаблон и распространи на каждый кейс». У остальных семи кейсов раздела с
   * такой меткой нет, а числа лежат в «Бизнес-эффекте», «После редизайна» и
   * «Внедрении и результатах». Пока поиск шёл по одной метке, блок цифр
   * существовал ровно у одного кейса.
   *
   * Берётся ПЕРВЫЙ раздел списка, в котором нашлись величины: порядок списка —
   * это порядок предпочтения, от прямых метрик к бизнес-следствиям.
   */
  for (const wanted of METRIC_SECTION_TITLES) {
    const section = caseStudy.detailSections?.find(
      (item) => (item.kicker ?? item.title) === wanted,
    )
    if (!section?.items?.length) continue
    const items = outcomesFromItems(section.items)
    if (items.length) return { items, title: wanted }
  }
  return null
}

/**
 * Разбор пунктов раздела в величины блока крупных цифр.
 *
 * 🔴 Не более четырёх — столько их в образце, и столько колонок в ряду. У
 * «Подписок» чисел шесть, и без предела ряд ломался на 4 + 2: последняя пара
 * висела под первым рядом обрубком. Отброшенные величины никуда не пропадают —
 * полная фраза остаётся в своём разделе кейса.
 */
function outcomesFromItems(source: string[], limit = 4): CaseOutcome[] {
  const outcomes: CaseOutcome[] = []
  for (const item of source) {
    if (outcomes.length === limit) break
    /*
     * Разбор тот же, что у полосы величин: сначала диапазон «с 62 до 74», потом
     * одиночная величина. Второго разбора чисел в файле быть не должно.
     */
    const range = RANGE.exec(item)
    const single = range ? null : SINGLE.exec(item)
    const value = range ? `${range[1].trim()} → ${range[2].trim()}` : single?.[1].trim()
    if (!value) continue

    /*
     * Метка есть только там, где автор сам назвал метрику до двоеточия
     * («Activation: доля…»). У остальных кейсов пункт — целая фраза, и
     * выдумывать ей имя нельзя: блок покажет цифру и суть без метки.
     */
    const colon = item.indexOf(":")
    const head = colon > 0 ? item.slice(0, colon).trim() : ""
    const label = head && head.length <= 28 ? head : ""

    /*
     * Из сути метрики вырезается «на <величина>» и «до <величина>»: число уже
     * стоит крупным, и во второй раз оно читается как другая цифра. Точка в
     * конце снимается тем же правилом, что у метрик, — сокращение «п.п.» им не
     * портится.
     *
     * 🔴 Предлог «до» добавлен вместе с единицами времени. Рост у автора записан
     * как «растёт НА 15–25%», а сокращение времени — как «сокращается ДО 20–35
     * секунд»: с одним предлогом подпись у «Флоу» повторяла крупное число
     * («20–35 секунд · сокращается до 20–35 секунд, раньше — 45–70»).
     */
    const note = withoutTrailingPeriod(
      (label ? item.slice(colon + 1) : item)
        .replace(new RegExp(`\\s*(?:на|до)\\s+${escapeForRegExp(value)}`), "")
        .trim(),
    )

    /*
     * Единица отрезается тем же `unitOf`, которым её считает `sameUnit` —
     * второго разбора величины в файле быть не должно.
     */
    const unit = unitOf(value)
    const amount = unit ? value.slice(0, value.length - unit.length).trim() : value

    outcomes.push({ amount, label, note, unit, value })
  }

  return outcomes
}

/** Величина уходит в регулярное выражение, а в ней есть точки и дефисы. */
function escapeForRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\-]/g, "\\$&")
}

/**
 * Числа кейса, поднятые из тела наверх.
 *
 * Ни одна цифра не сочиняется и не пересчитывается: `value` — это подстрока
 * исходного предложения. Фраза без числа строкой метрик не становится
 * (правило `supabase.com` → «нет значения — нет строки»), а величина в чужой
 * единице — не становится тоже, см. `sameUnit`.
 */
export function caseMetrics(caseStudy: CaseStudy, limit = 4): CaseMetric[] {
  const sources: string[][] = []
  for (const title of METRIC_SECTION_TITLES) {
    /*
     * 🔴 Раздел ищется по МЕТКЕ, а `title` — только запасной вариант.
     *
     * До 2026-08-14 метка и была заголовком, поэтому поиск шёл по нему. Когда у
     * разделов появились содержательные заголовки («Чем измеряли результат»),
     * поиск по `title` перестал находить что-либо, и строка величин на плоскости
     * «Итог» молча опустела бы. Поймано типами при первой же сборке.
     */
    const section = caseStudy.detailSections?.find(
      (item) => (item.kicker ?? item.title) === title,
    )
    /*
     * 🔴 Заголовок раздела читается ПЕРВЫМ, до пунктов, — и порядок значим.
     *
     * Утром 2026-08-14 в `title` стояло первое предложение содержания, и число
     * жило там. После переписывания текстов кейса `title` — тезис без цифр, а
     * величины вернулись в пункты; заголовок без числа отсеивается сам, потому
     * что фраза без величины строкой метрик не становится.
     *
     * Порядок трогать нельзя в обе стороны: первое найденное число уезжает на
     * синий экран `/archive` первой величиной компании A3. Поставь в тезис
     * цифру — и подписью там окажется обрывок тезиса вместо «Activation».
     */
    if (section?.items?.length) sources.push([section.title, ...section.items])
  }
  sources.push(caseStudy.result)

  for (const items of sources) {
    const metrics: CaseMetric[] = []
    for (const item of items) {
      const range = RANGE.exec(item)
      const single = range ? null : SINGLE.exec(item)
      const value = range
        ? `${range[1].trim()} → ${range[2].trim()}`
        : single?.[1].trim()
      if (!value) continue

      // Подпись величины — то, что стоит до двоеточия («Activation: рост доли…»),
      // если оно достаточно короткое; иначе вся фраза без точки в конце.
      const colon = item.indexOf(":")
      const head = colon > 0 ? item.slice(0, colon).trim() : ""
      const label = head && head.length <= 28 ? head : withoutTrailingPeriod(item)
      metrics.push({ label, value })
      if (metrics.length === limit) break
    }
    if (metrics.length > 0) return sameUnit(metrics)
  }

  return []
}

/**
 * «3 кейса» / «2 кейса» / «1 кейс» — русская форма числительного.
 *
 * Счётчик ПОКОМПАНИЙНЫЙ: он говорит, сколько работ открыто в этом разделе, и
 * стоит в мета-строке карточки компании. Сводного счётчика «8 кейсов» на
 * главной нет — он читался как «больше ничего нет», хотя показано только то,
 * что можно показывать.
 */
export function caseCountLabel(count: number): string {
  const mod100 = count % 100
  const mod10 = count % 10
  if (mod10 === 1 && mod100 !== 11) return `${count} кейс`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${count} кейса`
  return `${count} кейсов`
}

/**
 * Кейс-шаблон, по которому собраны все остальные страницы.
 *
 * Решение владельца 2026-08-17: «используй кейс А3 редизайн главной как шаблон».
 * Он единственный размечен по макету `95:1004`, и его разделы служат образцом
 * состава, порядка и — до появления своих текстов — временной рыбой.
 */
export const TEMPLATE_CASE_ID = "dashboard-redesign"

/** Разделы кейса-шаблона: источник рыбы для роли, которой у кейса нет. */
export function templateCaseSections(): CaseDetailSection[] {
  const company = companies.find((item) => item.id === "a3")
  const study = company?.cases.find((item) => item.id === TEMPLATE_CASE_ID)
  return study?.detailSections ?? []
}

/** Величины кейса-шаблона — рыба для блока цифр там, где своих чисел нет. */
export function templateCaseOutcomes(): { items: CaseOutcome[]; title: string } | null {
  const company = companies.find((item) => item.id === "a3")
  const study = company?.cases.find((item) => item.id === TEMPLATE_CASE_ID)
  return study ? caseOutcomes(study) : null
}

export function companyById(id: string): Company | undefined {
  return companies.find((company) => company.id === id)
}

export function caseById(company: Company, id: string): CaseStudy | undefined {
  return company.cases.find((item) => item.id === id)
}

