export interface CaseDetailSection {
  /**
   * Служебная метка раздела — «Контекст», «Цель», «Метрики успеха».
   *
   * Заведена 2026-08-14 по правке владельца: раньше это слово и было
   * заголовком, из-за чего разделы назывались одинаково во всех кейсах и не
   * говорили ничего о содержании. Теперь метка отвечает на вопрос «что это за
   * блок», а `title` — «о чём именно он здесь».
   */
  kicker?: string
  title: string
  body?: string[]
  items?: string[]
  quote?: string
  /**
   * Карточки раздела — заголовок и абзац под ним, сеткой два на два.
   *
   * 🔴 Заведено 2026-08-16 по узлу `124:2018`. Тот же текст лежал в `items`
   * одной строкой («Быстрые действия. Если вынести их…»), а в макете он разнесён
   * на две роли: имя гипотезы крупно и её формулировка абзацем. Разбирать строку
   * по первой точке было бы догадкой — роли заданы явно.
   */
  /**
   * Короткое имя раздела для бокового рельса лонгрида.
   *
   * Заведено 2026-09-11 вместе со схемой «рельс с оглавлением сбоку». В рельсе
   * стоят указатели, а не заголовки: строка «Подрядчик верит демо, когда узнаёт
   * свою механику» занимает там три строки и превращает список в стену. Метка
   * (`kicker`) подходит там, где она есть; у рассказных разделов её нет, и
   * короткое имя задаётся здесь явно, а не режется из заголовка по длине.
   */
  navLabel?: string
  /**
   * Пара «было → стало» вместо сплошного абзаца.
   *
   * Заведено 2026-09-11: владелец о прежней подаче — тринадцать разделов
   * одинаковой стеной. Половина рассказа устроена как сравнение прежнего
   * порядка с новым, и эта пара показывает разницу глазом, а не пересказом.
   * Текст берётся из того же раздела, а не дописывается: в паре стоят его
   * первые абзацы, остальное остаётся под ней обычным текстом.
   */
  compare?: { after: string; before: string }
  /**
   * Вынос на правое поле: величина и короткая подпись к ней.
   *
   * Там, где в разделе живёт число или короткий вывод, поле перестаёт быть
   * пустым. Приём страниц Apple HIG, где справа от текста стоят платформы и
   * оглавление. Величина необязательна — бывает вынос без числа.
   */
  aside?: { note: string; value?: string }
  cards?: { text: string; title: string }[]
  /**
   * Схема пути ВМЕСТО кадра.
   *
   * 🔴 Заведено 2026-08-17 по правке владельца: «отобрази флоу, который
   * описывается выше — просто схематично, чтобы не грузить рисунками, а просто
   * визуально показать путь». В макете на этом месте стоит серый плейсхолдер
   * `120:1566` (1800 × 664) под кадр; кадра решено не ставить.
   *
   * `entry` — общий путь до развилки, `tracks` — ветки задач. Устройство именно
   * такое, потому что тезис раздела говорит о развилке: человек шёл одним
   * входом, а дальше расходился по задачам, и часть ветвей упиралась в людей, а
   * не в экран.
   *
   * 🔴 В шагах НЕ называются разделы старого кабинета: его устройство мне
   * неизвестно, а правдоподобные названия были бы выдумкой. Каждая ступень взята
   * из текста самого кейса — «уходил в разделы меню или писал менеджеру» (тезис
   * «Контекста») и «статус заявки или подключения банка выяснял у менеджера»
   * (пятый пункт «Проблем»).
   */
  flow?: {
    caption: string
    entry: string[]
    tracks: { label: string; steps: string[] }[]
  }
  /**
   * Схемы того же блока: позиция становится слайдером.
   *
   * Заведено 2026-08-27. Место под схему в каркасе одно, а показать нужно
   * два состояния процесса — до системы и после. Порознь они не читаются:
   * смысл именно в сравнении, и слайдер держит их на одном месте страницы.
   */
  flowMore?: NonNullable<CaseDetailSection["flow"]>[]
  image?: CaseImage
  images?: CaseImage[]
  videos?: { caption: string; src: string }[]
  /*
   * ─── СЛУЖЕБНЫЕ ПОЛЯ КАРКАСА ───────────────────────────────────────────────
   * В данных их НЕТ и быть не должно: они заполняются в рантайме, когда страница
   * кейса раскладывает разделы по позициям шаблона «Редизайна главной» (правка
   * владельца 2026-08-17 «повтори расположение блоков включая порядок»).
   *
   * Живут здесь, а не в отдельном типе, потому что дальше идут тем же путём, что
   * и раздел: в один и тот же рендер. Отдельный тип-обёртка заставил бы рендер
   * знать про два вида разделов.
   */
  /** Блок стоит на трети ширины (`true`) или у поля. Иначе считается по порядку. */
  frameShift?: boolean
  /** Какой блок кадров идёт сразу за разделом — и рисуется местом, если кадра нет. */
  frameShots?: "pair" | "wide"
  /** За этим разделом идёт блок крупных цифр. */
  frameFigures?: boolean
  /**
   * Текст взят из кейса-шаблона как ВРЕМЕННАЯ рыба.
   *
   * 🔴 Владелец 2026-08-17: «проставь везде нужные блоки, даже если их нет; потом
   * просто допишем текст, а пока пускай будет тот, что из шаблона». То есть на
   * странице «Подписок» может стоять текст про платежи А3 — это заглушка, а не
   * факт о кейсе. Признак выносится в DOM (`data-placeholder`), чтобы такие блоки
   * было видно и в браузере, и в тестах, и чтобы их нельзя было спутать с
   * авторским текстом при публикации.
   */
  framePlaceholder?: boolean
}

