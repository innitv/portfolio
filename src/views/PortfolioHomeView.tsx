import { CardRow, CompanyCard } from "@/components/portfolio/company-card"
import { SiteFooter, SiteHeader } from "@/components/portfolio/site-chrome"
import { ShadcnThemeScope } from "@/components/shadcn/theme-scope"

import { companies, profile, type CompanyId } from "./portfolio.data"

/**
 * Главная — разводящая по компаниям.
 *
 * ─── ПЕРВЫЙ ЭКРАН ───────────────────────────────────────────────────────────
 * Раскладка собрана по мотивам блока `shadcnblocks.com/block/hero248` («Split
 * hero with overlapping team avatars in headline»), выбранного владельцем.
 * Блок платный, доступа к его коду нет и он не вскрывался — воспроизведён
 * приём: две колонки, слева крупный заголовок, ниже лид; правая колонка
 * пустая и существует ради меры строки.
 *
 * Главная черта оригинала — группа кружков, вшитая прямо в строку заголовка, —
 * держалась ровно один заход и убрана владельцем 2026-08-03; разбор причин
 * стоит у самого `h1` ниже. Осталась раскладка.
 *
 * КНОПКИ ПОД ЛИДОМ НЕТ, и это решение, а не пропуск. В оригинале там CTA, но
 * готовой строки для неё в контенте не существует: на сайте всего два глагола
 * действия — «Смотреть кейсы» на карточке компании (он требует выбрать, какой
 * именно) и метки контактов. Сочинять CTA нельзя, поэтому первый экран ведёт
 * не кнопкой, а секцией «Компании» сразу под ним: три конкретных перехода
 * вместо одной абстрактной кнопки.
 *
 * Фон первого экрана — пунктирная сетка с затуханием книзу и мягкий радиальный
 * подсвет (`background-pattern22`, тоже платный, тоже собран с нуля; механика в
 * `styles/portfolio.css`). Оба слоя рендерит ЭТОТ вид, поэтому на страницах
 * компании и кейса их нет по построению.
 */

export interface PortfolioHomeViewProps {
  onContact?: (channel: string) => void
  onOpenCompany: (companyId: CompanyId) => void
}

export function PortfolioHomeView({ onContact, onOpenCompany }: PortfolioHomeViewProps) {
  // Колонка на всю высоту окна: подвал прижат к низу, а не висит сразу за
  // содержимым. Разбор — комментарий к `main` ниже.
  return (
    <ShadcnThemeScope
      className="bg-background text-foreground relative isolate flex min-h-dvh flex-col"
      theme="portfolio"
    >
      <div aria-hidden="true" className="pf-hero-glow" data-testid="pf-hero-glow" />
      <div aria-hidden="true" className="pf-grid-pattern" data-testid="pf-grid-pattern" />

      {/* Имя в шапке не кликабельно: ссылка на текущую страницу — обещание
          перехода, которого не будет. */}
      <SiteHeader />

      {/* ─── ОБЩИЙ СТАРТ ЗАГОЛОВКА ─────────────────────────────────────────
          Отступ 32 / 48 px от низа шапки — эталон для ВСЕХ трёх страниц, и
          менять его надо разом во всех трёх видах. Замер до правки (верх
          коробки h1, 1440): главная 132, компания 124, кейс 100 — разброс 32
          px, при переходе заголовок прыгал. На 390: 124 / 116 / 108.
          Раньше разницу маскировала отдельная строка крошек под шапкой;
          когда крошки уехали в шапку, перескок стал виден. Заметил владелец.
          Держится проверкой `tests/portfolio-layout.check.mjs`.

          `flex-1` — то, чем подвал прижимается к низу окна.
          Замер до правки (1440×1200): страница компании А3 не скроллилась
          (`scrollHeight` 1200 = высоте окна), а подвал заканчивался на 1177 —
          под ним оставалось 23 px пустого хвоста контейнера. У «Самолета» та
          же страница длиннее (1303), поэтому при переключении между
          компаниями подвал прыгал. `min-h-dvh` тянул контейнер, но не
          распределял остаток: без растущего `main` лишняя высота оседала
          ПОД подвалом, а не над ним. Заметил владелец. */}
      <main className="pf-flow flex-1 pt-8 pb-4 md:pt-12">
        {/* Две колонки, правая пустая: она и задаёт заголовку меру, из-за
            которой он встаёт в две строки, а не растягивается на 1152. */}
        <section className="pf-container grid gap-10 lg:grid-cols-2">
          <div className="pb-4 md:pb-10">
            {/* ─── ПОЧЕМУ В ЗАГОЛОВКЕ НЕТ ЗНАКОВ КОМПАНИЙ ─────────────────
                Здесь стояла группа круглых знаков, вшитых в строку заголовка
                по приёму `hero248`. Убраны по решению владельца 2026-08-03
                после осмотра вблизи: при размере 49×49 из трёх знаков
                опознавался один. «a3» читался, знак Ростелекома превращался в
                чёрную каплю, знак Самолета — в кнопку воспроизведения.

                Приём держался на доказательстве «вот с кем я работал», но то
                же доказательство даёт секция «Компании» пятьюстами пикселями
                ниже — и даёт лучше: там логотипы идут со словами, 124×32 и
                129×20. Герой показывал те же бренды огрызками и проигрывал
                собственной секции.

                Замена на эмодзи рассматривалась и отклонена: они цветные, а
                хроматики в интерфейсе нет вовсе — цвет принадлежит только
                скриншотам работ; плюс их начертание зависит от платформы.
                Нейтральные иконки отклонены как декорация без сообщения. */}
            <h1 className="pf-h1 text-foreground">{profile.title}</h1>
            <p className="pf-lead text-muted-foreground mt-5 max-w-[52ch]">{profile.lead}</p>
          </div>
        </section>

        <section aria-labelledby="pf-companies-title" className="pf-container">
          <h2 className="pf-h3 text-foreground mb-6" id="pf-companies-title">
            Компании
          </h2>
          {/* Ряд, а не сетка карточек с зазором: карточки делят общую рамку и
              разделены линией, а не пустотой. */}
          <CardRow columns={3}>
            {companies.map((company) => (
              <CompanyCard company={company} key={company.id} onOpen={onOpenCompany} />
            ))}
          </CardRow>
        </section>
      </main>

      <SiteFooter onContact={onContact} />
    </ShadcnThemeScope>
  )
}
